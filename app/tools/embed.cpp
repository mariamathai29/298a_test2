// Build tool: writes the given files into a C++ source as byte arrays.
//   afx_embed out.cpp a.ttf b.ttf ...
// Each file becomes afx::embedded[i] (name, data, size), in order.

#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main (int argc, char** argv)
{
    if (argc < 2) return 1;
    std::FILE* out = std::fopen (argv[1], "w");
    if (out == nullptr) return 1;
    std::fprintf (out, "// Generated by afx_embed: do not edit.\n#include \"Fonts.h\"\n\nnamespace afx\n{\nnamespace\n{\n");
    std::vector<std::string> names;
    std::vector<size_t> sizes;
    for (int i = 2; i < argc; ++i)
    {
        std::ifstream in (argv[i], std::ios::binary);
        if (! in) return 1;
        const std::vector<unsigned char> bytes ((std::istreambuf_iterator<char> (in)), std::istreambuf_iterator<char>());
        std::string name = argv[i];
        name = name.substr (name.find_last_of ("/\\") + 1);
        names.push_back (name);
        sizes.push_back (bytes.size());
        std::fprintf (out, "const unsigned char data%d[] = {", i - 2);
        for (size_t k = 0; k < bytes.size(); ++k)
            std::fprintf (out, "%s%u,", k % 32 == 0 ? "\n" : "", bytes[k]);
        std::fprintf (out, "\n};\n");
    }
    std::fprintf (out, "} // namespace\n\nconst std::vector<Embedded>& embedded()\n{\n    static const std::vector<Embedded> list {\n");
    for (size_t i = 0; i < names.size(); ++i)
        std::fprintf (out, "        { \"%s\", data%zu, %zu },\n", names[i].c_str(), i, sizes[i]);
    std::fprintf (out, "    };\n    return list;\n}\n} // namespace afx\n");
    return std::fclose (out) == 0 ? 0 : 1;
}
