#include <cstddef>
#include <vector>

namespace afx
{
struct Embedded
{
    const char* name;
    const unsigned char* data;
    size_t size;
};
const std::vector<Embedded>& embedded();   // generated by tools/embed.cpp

enum class Face { sans, sansBold, serif, serifBold, mono, monoBold };
inline const Embedded& font (Face f) { return embedded()[(size_t) f]; }
} // namespace afx
